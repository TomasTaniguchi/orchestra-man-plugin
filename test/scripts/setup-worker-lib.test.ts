import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  createMachineToken,
  extractWorkerUrl,
  findDatabaseId,
  nodeVersionOk,
  renderConfig,
  validName,
  waitForHealth,
} from "../../scripts/setup-worker-lib.mjs";

const TEMPLATE = readFileSync(join(import.meta.dirname, "../../worker/wrangler.jsonc"), "utf8");

describe("setup-worker-lib", () => {
  it("checks the Node version", () => {
    expect(nodeVersionOk("22.13.0")).toBe(true);
    expect(nodeVersionOk("24.1.0")).toBe(true);
    expect(nodeVersionOk("22.12.9")).toBe(false);
    expect(nodeVersionOk("20.19.0")).toBe(false);
  });

  it("validates Worker and database names", () => {
    expect(validName("orchestra-man")).toBe(true);
    expect(validName("om2")).toBe(true);
    for (const bad of ["", "-om", "om-", "Orchestra", "om_man", "a".repeat(64)]) expect(validName(bad)).toBe(false);
  });

  it("finds a database id in `wrangler d1 list --json`, tolerating a banner", () => {
    const list = ` ⛅️ wrangler 4.156.0\n[{"uuid":"abc","name":"other"},{"uuid":"def","name":"orchestra-man"}]`;
    expect(findDatabaseId(list, "orchestra-man")).toBe("def");
    expect(findDatabaseId(list, "missing")).toBeNull();
    expect(findDatabaseId("no json here", "x")).toBeNull();
  });

  it("renders the personal config from the committed template", () => {
    const out = renderConfig(TEMPLATE, { workerName: "om-tomas", databaseName: "om-db", databaseId: "uuid-1" });
    expect(out).toMatch(/^\/\/ Generated by scripts\/setup-worker\.sh/);
    expect(out).toContain('"name": "om-tomas"');
    expect(out).toContain('"database_name": "om-db"');
    expect(out).toContain('"database_id": "uuid-1"');
    expect(out).not.toContain("REPLACE_WITH_YOUR_DATABASE_ID");
    expect(() => renderConfig("{}", { workerName: "a", databaseName: "b", databaseId: "c" })).toThrow(/did the template change\?/);
  });

  it("extracts the workers.dev URL from deploy output", () => {
    expect(extractWorkerUrl("Uploaded\n  https://orchestra-man.tomas.workers.dev\nCurrent Version ID")).toBe(
      "https://orchestra-man.tomas.workers.dev",
    );
    expect(extractWorkerUrl("Deployed with a custom domain only")).toBeNull();
  });

  it("retries the health check until the Worker answers", async () => {
    let calls = 0;
    const fetchFn = (async () => {
      calls += 1;
      if (calls < 3) throw new Error("not yet");
      return Response.json({ status: "ok" });
    }) as typeof fetch;
    await expect(waitForHealth("https://w.dev", { delayMs: 1, fetchFn })).resolves.toEqual({ status: "ok" });
    await expect(waitForHealth("https://w.dev", { attempts: 2, delayMs: 1, fetchFn: (async () => new Response("", { status: 503 })) as typeof fetch })).rejects.toThrow(/did not respond/);
  });

  it("reports why a machine token could not be created", async () => {
    const fetchFn = (async () => Response.json({ error: { code: "unauthorized", message: "invalid or revoked token" } }, { status: 401 })) as typeof fetch;
    await expect(createMachineToken("https://w.dev", "bad", "laptop", fetchFn)).rejects.toThrow(/HTTP 401 invalid or revoked token/);
  });
});
