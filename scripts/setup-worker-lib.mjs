// Helpers for scripts/setup-worker.sh. Everything that differs between macOS, Linux and
// Windows shells (JSON, HTTP, random bytes, file edits) runs here, in Node, the same everywhere.
// Usage: node scripts/setup-worker-lib.mjs <command> [args...]   (stdin is read where noted)
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const MIN_NODE = [22, 13];
export const NAME_PATTERN = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;
const PLACEHOLDER_ID = "REPLACE_WITH_YOUR_DATABASE_ID";

export function nodeVersionOk(version = process.versions.node) {
  const [major, minor] = version.split(".").map(Number);
  return major > MIN_NODE[0] || (major === MIN_NODE[0] && minor >= MIN_NODE[1]);
}

/** Worker and D1 names: lowercase letters, digits and inner dashes, at most 63 characters. */
export const validName = (name) => NAME_PATTERN.test(name);

/** Finds a database id by name in the output of `wrangler d1 list --json`. */
export function findDatabaseId(listJson, name) {
  const start = listJson.indexOf("[");
  if (start === -1) return null;
  const list = JSON.parse(listJson.slice(start));
  const db = list.find((d) => d.name === name);
  return db ? (db.uuid ?? db.id ?? db.database_id ?? null) : null;
}

/**
 * Builds the personal wrangler config from the committed template. Fails loudly if the template
 * changed shape, instead of silently writing a config that deploys somewhere unexpected.
 */
export function renderConfig(template, { workerName, databaseName, databaseId }) {
  const replacements = [
    [/"name":\s*"orchestra-man"/, `"name": "${workerName}"`],
    [/"database_name":\s*"orchestra-man"/, `"database_name": "${databaseName}"`],
    [PLACEHOLDER_ID, databaseId],
  ];
  let out = template;
  for (const [pattern, value] of replacements) {
    if (!(typeof pattern === "string" ? out.includes(pattern) : pattern.test(out)))
      throw new Error(`worker/wrangler.jsonc no tiene ${pattern}; ¿cambió la plantilla?`);
    out = out.replace(pattern, value);
  }
  return `// Generated by scripts/setup-worker.sh for your own deployment. Not committed (.gitignore).\n${out}`;
}

/** The workers.dev URL wrangler prints after a deploy, or null. */
export function extractWorkerUrl(deployOutput) {
  return deployOutput.match(/https:\/\/[a-z0-9.-]+\.workers\.dev\b/i)?.[0] ?? null;
}

export async function waitForHealth(url, { attempts = 10, delayMs = 3000, fetchFn = fetch } = {}) {
  for (let i = 0; i < attempts; i++) {
    try {
      const response = await fetchFn(new URL("/v1/health", url), { signal: AbortSignal.timeout(10_000) });
      if (response.ok) return await response.json();
    } catch {
      // A fresh deploy can take a few seconds to propagate.
    }
    if (i < attempts - 1) await new Promise((r) => setTimeout(r, delayMs));
  }
  throw new Error(`el Worker no respondió en ${new URL("/v1/health", url)}`);
}

export async function createMachineToken(url, adminToken, name, fetchFn = fetch) {
  const response = await fetchFn(new URL("/v1/admin/tokens", url), {
    method: "POST",
    headers: { authorization: `Bearer ${adminToken}`, "content-type": "application/json" },
    body: JSON.stringify({ name }),
  });
  const body = await response.json().catch(() => ({}));
  if (response.status !== 201) throw new Error(`no se pudo crear el token: HTTP ${response.status} ${body?.error?.message ?? ""}`);
  return body.token;
}

const readStdin = async () => {
  let data = "";
  for await (const chunk of process.stdin) data += chunk;
  return data;
};

const COMMANDS = {
  "node-version-ok": async () => (nodeVersionOk() ? 0 : 1),
  "valid-name": async (name) => (validName(name ?? "") ? 0 : 1),
  "random-hex": async () => (console.log(randomBytes(32).toString("hex")), 0),
  /** stdin: `wrangler d1 list --json` output. Prints the id, or nothing. */
  "find-db": async (name) => {
    const id = findDatabaseId(await readStdin(), name);
    if (id) console.log(id);
    return 0;
  },
  "write-config": async (template, out, workerName, databaseName, databaseId) => {
    if (!existsSync(template)) throw new Error(`no existe ${template}`);
    writeFileSync(out, renderConfig(readFileSync(template, "utf8"), { workerName, databaseName, databaseId }));
    return 0;
  },
  /** stdin: deploy output. */
  "extract-url": async () => {
    const url = extractWorkerUrl(await readStdin());
    if (url) console.log(url);
    return 0;
  },
  health: async (url) => (console.log(JSON.stringify(await waitForHealth(url))), 0),
  /** stdin: the admin token (kept out of the process list). */
  "create-token": async (url, name) => (console.log(await createMachineToken(url, (await readStdin()).trim(), name)), 0),
};

async function main([command, ...args]) {
  const run = COMMANDS[command];
  if (!run) {
    console.error(`comando desconocido: ${command}. Comandos: ${Object.keys(COMMANDS).join(", ")}`);
    return 2;
  }
  return run(...args);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (error) => {
      console.error(`error: ${error.message}`);
      process.exit(1);
    },
  );
}
