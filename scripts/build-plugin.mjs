// Bundles the plugin runtime into plugin/dist so users install it without npm install.
import { cpSync, mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";

const root = join(import.meta.dirname, "..");
const outdir = join(root, "plugin", "dist");

rmSync(outdir, { recursive: true, force: true });
mkdirSync(outdir, { recursive: true });

await build({
  entryPoints: { mcp: join(root, "src/plugin/bin/mcp.ts"), cli: join(root, "src/plugin/bin/cli.ts") },
  outdir,
  outExtension: { ".js": ".mjs" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  legalComments: "none",
  // Minified to keep the committed bundle small; names are kept so stack traces stay readable.
  minify: true,
  keepNames: true,
  // Some CommonJS dependencies call require(); give the ESM bundle one.
  banner: { js: "// Generated by scripts/build-plugin.mjs. Do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: "warning",
});

cpSync(join(root, "migrations"), join(outdir, "migrations"), { recursive: true });
console.log(`built ${outdir}`);
